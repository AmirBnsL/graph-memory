#!/usr/bin/env python3
"""Generate the ledger's tables from results/*.json.

Hand-editing results/INDEX.md is how prose numbers drift from the JSONs that
produced them -- the same failure class the thesis is about. This regenerates
the run tables from the committed result files, so the ledger can only be
stale, never wrong.

    python src/make_tables.py            # print markdown to stdout

Then paste into results/INDEX.md. Every row carries the file it came from, so
any number in the ledger is traceable in one step.
"""
from __future__ import annotations

import glob
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"

CAT_NAMES = {
    "locomo": {
        1: "multi-hop",
        2: "temporal",
        3: "open-domain",
        4: "single-hop",
        5: "adversarial",
    },
    "longmemeval": {
        1: "extraction",
        2: "multi-session",
        3: "temporal",
        4: "update",
        5: "abstention",
    },
}


def load_runs() -> list[dict]:
    """Latest result per (benchmark, mode, retriever, k). Rescored files are derived
    artifacts: they carry the same numbers under a new name, so skip them."""
    runs: dict[tuple, dict] = {}
    for f in sorted(glob.glob(str(RESULTS / "*.json"))):
        p = Path(f)
        if p.name.endswith(".manifest.json") or "_probe" in p.name:
            continue
        try:
            d = json.loads(p.read_text())
        except json.JSONDecodeError:
            continue
        if not isinstance(d, dict) or "mode" not in d or "rows" not in d:
            continue
        key = (d.get("benchmark", "locomo"), d.get("mode"), (d.get("retriever") or ""), int(d.get("k") or 0))
        runs[key] = d
    return [runs[k] for k in sorted(runs, key=lambda t: (t[0], t[1], t[2], t[3]))]


def fmt(v, nd=3) -> str:
    return "–" if v is None else f"{v:.{nd}f}"


def print_h1_decomposition(runs: list[dict]) -> None:
    """Print H1 (Structure vs Extraction) decomposition tables."""
    # Group by (benchmark, retriever, k)
    groups: dict[tuple, dict[str, dict]] = {}
    for d in runs:
        b = d.get("benchmark", "locomo")
        retr = d.get("retriever") or "all-MiniLM-L6-v2"
        k = int(d.get("k") or 0)
        mode = d.get("mode", "")
        key = (b, retr, k)
        if key not in groups:
            groups[key] = {}
        groups[key][mode] = d

    # Only print if any memory backends exist
    has_memory = any(
        any(m.startswith("memory_") for m in mode_map)
        for mode_map in groups.values()
    )
    if not has_memory:
        return

    print("\n### Hypothesis 1: Structure vs. Extraction Decomposition (F1)\n")
    print("| benchmark | retriever | k | Vector (Raw) | Flat (No Graph) | HippoRAG | Hippo Flattened | Bi-Temporal | Δ_extraction | Δ_structure | Δ_ablation | Δ_temporal |")
    print("|---|---|---|---|---|---|---|---|---|---|---|---|")

    for (b, retr, k), mm in sorted(groups.items()):
        if not any(m.startswith("memory_") for m in mm):
            continue
        v_run = mm.get("vector")
        f_run = mm.get("memory_flat")
        h_run = mm.get("memory_hipporag")
        hf_run = mm.get("memory_hipporag_flattened")
        t_run = mm.get("memory_temporal_bteg")

        f1_metric = "F1_answerable"  # Honest comparison metric on answerable questions

        v_val = v_run.get(f1_metric) if v_run else None
        f_val = f_run.get(f1_metric) if f_run else None
        h_val = h_run.get(f1_metric) if h_run else None
        hf_val = hf_run.get(f1_metric) if hf_run else None
        t_val = t_run.get(f1_metric) if t_run else None

        # Deltas
        d_ext = (f_val - v_val) if (f_val is not None and v_val is not None) else None
        d_struct = (h_val - f_val) if (h_val is not None and f_val is not None) else None
        d_ablate = (h_val - hf_val) if (h_val is not None and hf_val is not None) else None
        d_temp = (t_val - f_val) if (t_val is not None and f_val is not None) else None

        print(f"| {b} | {retr} | {k} | {fmt(v_val)} | {fmt(f_val)} | {fmt(h_val)} | {fmt(hf_val)} | {fmt(t_val)} "
              f"| {fmt(d_ext)} | {fmt(d_struct)} | {fmt(d_ablate)} | {fmt(d_temp)} |")


def main() -> None:
    runs = load_runs()
    if not runs:
        print("no results yet")
        return

    print("<!-- GENERATED by src/make_tables.py -- do not edit by hand -->\n")
    print("### All runs (latest per benchmark · mode · retriever · k)\n")
    print("| benchmark | mode | k | retriever | n | F1 | F1_paper | EM | F1_answerable | "
          "refusal_acc | recall_any | recall_all | coverage | prompt chars | latency s |")
    print("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for d in runs:
        b = d.get("benchmark", "locomo")
        print(f"| {b} | {d['mode']} | {d['k']} | {d.get('retriever') or 'all-MiniLM-L6-v2'} "
              f"| {d['n']} | {fmt(d.get('F1'))} | {fmt(d.get('F1_paper'))} "
              f"| {fmt(d.get('EM'))} | {fmt(d.get('F1_answerable'))} "
              f"| {fmt(d.get('refusal_accuracy'))} | {fmt(d.get('recall_any'))} "
              f"| {fmt(d.get('recall_all'))} | {fmt(d.get('evidence_coverage'))} "
              f"| {d.get('mean_prompt_chars', 0):.0f} "
              f"| {d.get('mean_latency_s', 0):.2f} |")

    print_h1_decomposition(runs)

    for b in ("locomo", "longmemeval"):
        b_runs = [d for d in runs if d.get("benchmark", "locomo") == b and d.get("recall_any_by_category")]
        if not b_runs:
            continue
        cats = CAT_NAMES[b]
        print(f"\n### Retrieval recall by category: {b}\n")
        print("| mode | k | " + " | ".join(cats[c] for c in sorted(cats)) + " | overall |")
        print("|---|---|" + "---|" * (len(cats) + 1))
        for d in b_runs:
            cells = " | ".join(
                fmt(d["recall_any_by_category"].get(str(c) if str(c) in d["recall_any_by_category"] else c))
                for c in sorted(cats))
            print(f"| {d['mode']} | {d['k']} | {cells} | {fmt(d.get('recall_any'))} |")


if __name__ == "__main__":
    main()
